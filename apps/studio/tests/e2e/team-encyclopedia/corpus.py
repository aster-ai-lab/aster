def filler(files: int = 15, sections: int = 10, seed: int = 20261013) -> list[tuple[str, str, str]]:
    """Weekly meeting notes: plausible distractors with shared vocabulary."""
    rng = random.Random(seed)
    docs = []
    for week in range(1, files + 1):
        parts = [f"# 第{week}周例会纪要\n"]
        for team in rng.sample(TEAMS, sections):
            parts.append(
                f"\n## 第{week}周{team}进展\n\n{team}本周{rng.choice(DONE)}，"
                f"下周计划{rng.choice(PLAN)}，风险：{rng.choice(RISK)}。"
                f"如需申请资源请在系统中提交，审批后执行。\n"
            )
        docs.append((f"第{week:02d}周例会纪要.md", "all", "".join(parts)))
    return docs


