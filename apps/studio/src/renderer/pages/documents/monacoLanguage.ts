const LANGUAGE_BY_BASENAME: Readonly<Record<string, string>> = {
  dockerfile: 'dockerfile',
  gemfile: 'ruby',
  rakefile: 'ruby',
  jakefile: 'javascript',
  config: 'ini',
  '.editorconfig': 'ini',
  '.gitattributes': 'ini',
  '.gitconfig': 'ini',
  '.babelrc': 'json',
  '.eslintrc': 'json',
  '.prettierrc': 'json'
}

/** Monaco grammar for a file. Unknown names stay plaintext so they can still be edited. */
export function monacoLanguage(fileName: string): string {
  const base = fileName.replaceAll('\\', '/').split('/').pop()?.toLowerCase() ?? ''
  if (base === 'dockerfile' || base.startsWith('dockerfile.')) return 'dockerfile'
  if (base === '.env' || base.startsWith('.env.')) return 'shell'
  const named = LANGUAGE_BY_BASENAME[base]
  if (named) return named
  return LANGUAGE_BY_EXTENSION[fileExtension(base)] ?? 'plaintext'
}
