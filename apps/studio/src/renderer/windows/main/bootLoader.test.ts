import { describe, expect, it } from 'vitest'

import { stampTenantHtml } from '../../../../scripts/studioTenantBrand'
import html from './index.html?raw'

describe('main window boot loader', () => {
  it('keeps the aster star available before the application mounts', () => {
    const branded = stampTenantHtml(html, { slug: 'aster', product: 'AsterDream', brand: '#005ABB' })
    const parsed = new DOMParser().parseFromString(branded, 'text/html')
    const mark = parsed.querySelector('#spinner img[data-ui="page.loader.wordmark"]')
    expect(mark?.getAttribute('src')).toBe('/tenant-mark.png')
    expect(mark?.classList.contains('aster-dream-mark')).toBe(true)
    expect(branded).toContain("html[data-tenant='aster'] .boot-loader .towork-wordmark-draw")
    expect(parsed.documentElement.getAttribute('data-tenant')).toBe('aster')
    expect(parsed.title).toBe('AsterDream')
  })

  it('retains the ToWork wordmark animation and ring beside the tenant-specific mark', () => {
    const parsed = new DOMParser().parseFromString(html, 'text/html')
    const mark = parsed.querySelector('#spinner [data-ui="page.loader.wordmark"]')
    expect(parsed.getElementById('spinner')?.getAttribute('role')).toBe('status')
    expect(parsed.querySelectorAll('#spinner')).toHaveLength(1)
    expect(mark?.getAttribute('viewBox')).toBe('140 116 2164 512')
    expect(mark?.getAttribute('stroke-width')).toBe('76')
    expect(parsed.querySelectorAll('#spinner .towork-stroke')).toHaveLength(6)
    expect(parsed.querySelector('#spinner .is-o1')?.getAttribute('transform')).toBe('rotate(-90 606 432)')
    expect(parsed.querySelector('#spinner .is-o2')?.getAttribute('transform')).toBe('rotate(-90 1577.9 432)')
    expect(parsed.querySelector('#spinner .is-t')?.getAttribute('pathLength')).toBe('1')
    expect(parsed.querySelector('#spinner .boot-handoff > [data-ui="page.loader.wordmark"]')).toBe(mark)
    expect(parsed.querySelector('#spinner .boot-handoff > .page-loader-ring [data-ui="page.loader.ring"]')).toBeTruthy()
    expect(html).toContain('stroke-dasharray="28 85"')
    expect(html).toContain('@keyframes pageLoaderSpin')
    expect(html).toContain('animation-duration: 0.5s')
    expect(html).toContain('animation-iteration-count: 1;')
    expect(html).not.toContain('animation-iteration-count: infinite')
    expect(html).toContain('animation: pageLoaderMarkOut 180ms ease 800ms both')
    expect(html).toContain('animation: pageLoaderRingIn 180ms ease 800ms both')
    expect(html).toContain('@keyframes toworkDrawK')
    expect(parsed.querySelector('.cherry-boot')).toBeNull()
    expect(parsed.querySelector('.mark-kense')).toBeNull()
    expect(parsed.querySelector('.mark-a3s')).toBeNull()
    expect(parsed.querySelector('.mark-toyou')).toBeNull()
    expect(parsed.querySelector('[data-draw]')).toBeNull()
    expect(parsed.documentElement.hasAttribute('data-tenant')).toBe(false)
    expect(html).toContain('document.documentElement.dataset.a3sProduct')
    const bootBar = parsed.getElementById('applet-boot-bar')
    expect(bootBar?.hasAttribute('hidden')).toBe(true)
    expect(bootBar?.querySelector('[data-applet-boot="close"]')).toBeTruthy()
    expect(html).toContain("invoke('plugin:window|' + name, { label: label })")
    expect(html).toContain("params.get('workbench-applet')")
    expect(html).toContain("inbox: '任务'")
    expect(html).not.toContain('消息中心')
  })
})
