#[test]
#[ignore = "requires the paired native Aster/ACP and original kimi/k3.1-pro ACL"]
fn kimi_patch_single_multi_file_and_conflict_preserve_exact_transaction_scope() {
    let mut tui = start("tool-wave-patch", &[]);
    let seed = uuid::Uuid::new_v4().to_string();
    let a = tui.workspace.join("alpha.txt");
    let b = tui.workspace.join("beta.txt");
    let original_a = format!("ALPHA-{seed}\n");
    let original_b = format!("BETA-{seed}\n");
    std::fs::write(&a, &original_a).unwrap();
    std::fs::write(&b, &original_b).unwrap();
    let first = format!("FIRST-{seed}\n");
    let facts = request(&mut tui, "single", "patch", json!({
        "file_path":"alpha.txt","diff":format!("@@ -1 +1 @@\n-ALPHA-{seed}\n+FIRST-{seed}\n")
    }), "After a successful patch, use read on alpha.txt to independently verify its exact contents. Do not use write, edit or bash.");
    assert_eq!(one(&facts, "patch")["exit_code"], 0);
    assert_eq!(std::fs::read(&a).unwrap(), first.as_bytes());
    assert_eq!(std::fs::read(&b).unwrap(), original_b.as_bytes());
    tui.record("single-patch-bytes", "one native patch changes only alpha; an independent real read verifies the exact host-generated bytes");

    let final_a = format!("FINAL-A-{seed}\n");
    let final_b = format!("FINAL-B-{seed}\n");
    let facts = request(&mut tui, "multi", "patch", json!({"patches":[
        {"file_path":"alpha.txt","diff":format!("@@ -1 +1 @@\n-FIRST-{seed}\n+FINAL-A-{seed}\n")},
        {"file_path":"beta.txt","diff":format!("@@ -1 +1 @@\n-BETA-{seed}\n+FINAL-B-{seed}\n")}
    ]}), "After a successful patch, use read on alpha.txt and beta.txt to independently verify both exact results. Do not use write, edit or bash.");
    assert_eq!(one(&facts, "patch")["exit_code"], 0);
    assert_eq!(std::fs::read(&a).unwrap(), final_a.as_bytes());
    assert_eq!(std::fs::read(&b).unwrap(), final_b.as_bytes());
    tui.record(
        "multi-patch-bytes",
        "one patches call changes both files to their exact expected contents",
    );

    let facts = request(&mut tui, "conflict", "patch", json!({"patches":[
        {"file_path":"alpha.txt","diff":format!("@@ -1 +1 @@\n-FINAL-A-{seed}\n+SHOULD-NOT-COMMIT\n")},
        {"file_path":"beta.txt","diff":"@@ -1 +1 @@\n-NONEXISTENT-CONTEXT\n+SHOULD-NOT-COMMIT\n"}
    ]}), "If the patch fails, report the actual failure and read both files once to verify the failure scope. Do not retry, repair or call other tools.");
    assert_eq!(one(&facts, "patch")["is_error"], true);
    assert_eq!(std::fs::read(&a).unwrap(), final_a.as_bytes());
    assert_eq!(std::fs::read(&b).unwrap(), final_b.as_bytes());
    tui.record("multi-patch-conflict-atomic", "a valid alpha hunk followed by conflicting beta changes neither file; the real failure receipt is retained");
    finish(tui, "tool-wave-patch");
}

#[test]
#[ignore = "requires the paired native Aster/ACP and original kimi/k3.1-pro ACL"]
fn kimi_git_fixture_status_diff_branch_and_bad_checkout_are_owned() {
    let root = std::env::current_dir().unwrap().join(".tmp");
    let fixture = tempfile::Builder::new()
        .prefix("native-git-acceptance-")
        .tempdir_in(&root)
        .unwrap();
    let path = fixture.path();
    git(
        path,
        &[
            "-c",
            "init.templateDir=",
            "init",
            "--quiet",
            "-b",
            "fixture",
        ],
    );
    git(path, &["config", "core.autocrlf", "false"]);
    git(path, &["config", "core.hooksPath", ".git/no-hooks"]);
    std::fs::create_dir_all(path.join(".git/info")).unwrap();
    std::fs::write(path.join(".git/info/exclude"), ".a3s/\n").unwrap();
    std::fs::write(path.join("tracked.txt"), "ORIGINAL\n").unwrap();
    git(path, &["add", "--", "tracked.txt"]);
    git(
        path,
        &[
            "-c",
            "user.name=Aster Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "commit",
            "--quiet",
            "-m",
            "fixture",
        ],
    );
    let head = git(path, &["rev-parse", "HEAD"]);
    let changed = format!("CHANGED-{}\n", uuid::Uuid::new_v4());
    std::fs::write(path.join("tracked.txt"), &changed).unwrap();
    let mut tui = LiveTui::new("tool-wave-git");
    tui.workspace = path.to_path_buf();
    launch(&mut tui, &[]);
    let facts = request(
        &mut tui,
        "git-status",
        "git",
        json!({"command":"status"}),
        "Report the exact status. Do not call other tools.",
    );
    let status = one(&facts, "git");
    assert_eq!(status["exit_code"], 0);
    assert!(status["text"].as_str().unwrap().contains("tracked.txt"));
    let facts = request(
        &mut tui,
        "git-diff",
        "git",
        json!({"command":"diff"}),
        "Report the actual diff without changing it. Do not call other tools.",
    );
    let diff = one(&facts, "git");
    assert_eq!(diff["exit_code"], 0);
    let text = diff["text"].as_str().unwrap();
    assert!(text.contains("-ORIGINAL") && text.contains(changed.trim()));
    tui.record("fixture-git-read", "the actual git tool reports the tracked modification and exact diff in a repo under this workspace's .tmp");
    let branch = format!("acceptance-{}", uuid::Uuid::new_v4());
    let facts = request(&mut tui, "git-branch", "git", json!({"command":"branch","name":branch}), "After success, independently verify by calling git with command=branch and no name. Do not checkout, commit or call other tools.");
    let results = outputs(&facts, "git");
    assert_eq!(results.len(), 2);
    assert!(results.iter().all(|r| r["exit_code"] == 0));
    assert_eq!(
        git(path, &["rev-parse", &format!("refs/heads/{branch}")]),
        head
    );
    assert_eq!(git(path, &["branch", "--show-current"]).trim(), "fixture");
    let facts = request(
        &mut tui,
        "git-bad-checkout",
        "git",
        json!({"command":"checkout","ref":"missing-acceptance-ref"}),
        "Report the actual failure without retrying, creating a branch or calling other tools.",
    );
    assert_eq!(one(&facts, "git")["is_error"], true);
    assert_eq!(git(path, &["rev-parse", "HEAD"]), head);
    assert_eq!(git(path, &["branch", "--show-current"]).trim(), "fixture");
    assert_eq!(
        std::fs::read(path.join("tracked.txt")).unwrap(),
        changed.as_bytes()
    );
    tui.record("fixture-git-owned-mutation", "approved branch creation targets only the fixture; invalid checkout preserves current branch, HEAD and exact dirty file bytes");
    finish(tui, "tool-wave-git");
}

