#[test]
#[ignore = "requires the paired native Aster/ACP and original kimi/k3.1-pro ACL"]
fn kimi_update_plan_replaces_the_real_checklist_and_status_projection() {
    let mut tui = start("tool-wave-checklist", &[]);
    let facts = request(&mut tui, "checklist-first", "update_plan", json!({"plan":[
        {"id":"row-a","step":"CHECKLIST-FIRST","status":"in_progress"},
        {"id":"row-b","step":"CHECKLIST-SECOND","status":"pending"},
        {"id":"row-old","step":"CHECKLIST-REMOVED","status":"pending"}
    ]}), "This is a UI checklist fixture. Report the returned checklist result without performing the listed work or calling other tools.");
    let output = one(&facts, "update_plan");
    assert_eq!(output["exit_code"], 0);
    assert!(output["text"].as_str().unwrap().contains("0/3 done"));
    if !tui.screen().contains("CHECKLIST-REMOVED") {
        tui.bytes(b"\x14");
    }
    let screen = tui.wait_for("CHECKLIST-REMOVED", 8);
    assert!(screen.contains("CHECKLIST-FIRST") && screen.contains("CHECKLIST-SECOND"));
    tui.record(
        "checklist-first-ui",
        "a real update_plan receipt and ACP projection render all three requested checklist rows",
    );
    let facts = request(&mut tui, "checklist-replace", "update_plan", json!({"plan":[
        {"id":"row-b","step":"CHECKLIST-SECOND","status":"completed"},
        {"id":"row-a","step":"CHECKLIST-FIRST","status":"cancelled"}
    ]}), "This replaces the UI checklist fixture. Report the returned result without performing the listed work or calling other tools.");
    let output = one(&facts, "update_plan");
    assert_eq!(output["exit_code"], 0);
    assert!(output["text"].as_str().unwrap().contains("1/2 done"));
    let deadline = Instant::now() + Duration::from_secs(8);
    let screen = loop {
        let screen = tui.pump(80);
        if !screen.contains("CHECKLIST-REMOVED")
            && screen.contains("CHECKLIST-SECOND")
            && screen.contains("CHECKLIST-FIRST")
        {
            break screen;
        }
        assert!(
            Instant::now() < deadline,
            "checklist replacement not projected\n{screen}"
        );
    };
    assert!(screen.find("CHECKLIST-SECOND").unwrap() < screen.find("CHECKLIST-FIRST").unwrap());
    let packets = trace_packets(&tui);
    let plans = packets
        .iter()
        .filter(|p| {
            p["method"] == "session/update" && p["params"]["update"]["sessionUpdate"] == "plan"
        })
        .map(|p| &p["params"]["update"]["entries"])
        .collect::<Vec<_>>();
    let last = plans
        .last()
        .expect("actual ACP checklist update")
        .as_array()
        .unwrap();
    assert_eq!(last.len(), 2);
    assert_eq!(last[0]["content"], "CHECKLIST-SECOND");
    assert_eq!(last[0]["status"], "completed");
    assert_eq!(last[1]["content"], "CHECKLIST-FIRST");
    assert_eq!(last[1]["_meta"]["a3sStatus"], "cancelled");
    tui.record("checklist-replacement-ui", "replacement removes the old row, changes the order and projects completed/cancelled statuses independently of Plan review mode");
    finish(tui, "tool-wave-checklist");
}

#[test]
#[ignore = "requires the paired native Aster/ACP and original kimi/k3.1-pro ACL"]
fn kimi_background_start_tail_stop_terminates_the_owned_process_without_late_write() {
    let mut tui = start("tool-wave-background", &[]);
    let token = format!("BG-PROOF-{}", uuid::Uuid::new_v4());
    let command = if cfg!(windows) {
        format!("Write-Output '{token}'; Start-Sleep -Seconds 60; [IO.File]::WriteAllText('late-background.txt', 'SHOULD-NOT-EXIST')")
    } else {
        format!("printf '%s\\n' '{token}'; sleep 60; printf SHOULD-NOT-EXIST > late-background.txt")
    };
    let verification = if cfg!(windows) {
        "if (Test-Path -LiteralPath late-background.txt) { throw 'UNEXPECTED-LATE-FILE' }; Write-Output 'CANCEL-CONFIRMED'"
    } else {
        "test ! -e late-background.txt && printf CANCEL-CONFIRMED"
    };
    let prompt = format!("Call background with action='start', name='owned-job', and this exact command: {command}. Then call background with action='tail', name='owned-job', wait_for='{token}', timeout_ms=10000. Once you see that output, immediately call background action='stop' name='owned-job', then background action='tail' name='owned-job' timeout_ms=1000. Finally use bash once to independently verify cancellation with this exact command: {verification}. Report the real task identity, captured output and final state. Do not start another task, retry tools or create other files.");
    let facts = tui.turn(&prompt, Some(b"\r"));
    let results = outputs(&facts, "background");
    assert_eq!(results.len(), 4);
    assert!(results[..3].iter().all(|r| r["exit_code"] == 0));
    assert!(results[1]["text"].as_str().unwrap().contains(&token));
    assert_eq!(results[0]["metadata"]["name"], "owned-job");
    assert!(results[0]["metadata"]["workspace_child"]
        .as_str()
        .is_some_and(|s| !s.is_empty()));
    assert_eq!(results[1]["metadata"]["found"], true);
    assert_eq!(results[3]["is_error"], true);
    assert!(results[3]["text"]
        .as_str()
        .unwrap()
        .contains("no background task named 'owned-job' in this Run"));
    assert!(one(&facts, "bash")["text"]
        .as_str()
        .unwrap()
        .contains("CANCEL-CONFIRMED"));
    let deadline = Instant::now() + Duration::from_secs(61);
    while Instant::now() < deadline {
        assert!(
            !tui.workspace.join("late-background.txt").exists(),
            "cancelled process performed a late write"
        );
        tui.pump(100);
    }
    tui.record("background-owned-stop-no-late-write", "real start/tail/stop/tail receipts and an independent native shell verification are followed by 61 seconds without the delayed file effect");
    finish(tui, "tool-wave-background");
}

#[test]
#[ignore = "requires the paired native Aster/ACP and original kimi/k3.1-pro ACL"]
fn kimi_task_two_real_children_have_distinct_identity_outputs_and_parent_barrier() {
    let mut tui = start("tool-wave-task-children", &[]);
    let parent = tui.session_id();
    tui.dismiss();
    let a = format!("CHILD-A-{}", uuid::Uuid::new_v4());
    let b = format!("CHILD-B-中文-{}", uuid::Uuid::new_v4());
    std::fs::write(tui.workspace.join("child-a.txt"), &a).unwrap();
    std::fs::write(tui.workspace.join("child-b.txt"), &b).unwrap();
    let facts = request(&mut tui, "task-pair", "task", json!({"tasks":[
        {"agent":"explore","description":"ACCEPTANCE-CHILD-A","prompt":"Use read exactly once to read child-a.txt and reply with its exact contents. Do not call other tools, modify files, or read child-b.txt.","max_steps":4},
        {"agent":"explore","description":"ACCEPTANCE-CHILD-B","prompt":"Use read exactly once to read child-b.txt and reply with its exact contents. Do not call other tools, modify files, or read child-a.txt.","max_steps":4}
    ],"allow_partial_failure":false,"timeout_ms":120000}), "Wait for both real children. Report their actual returned outputs in input order. The parent must not directly read either child file, repeat the task or call other tools.");
    let output = one(&facts, "task");
    assert_eq!(output["exit_code"], 0);
    let children = output["metadata"]["results"].as_array().unwrap();
    assert_eq!(children.len(), 2);
    assert!(children.iter().all(|c| c["success"] == true));
    assert_ne!(children[0]["task_id"], children[1]["task_id"]);
    assert_ne!(children[0]["session_id"], children[1]["session_id"]);
    for (child, token, other) in [(&children[0], &a, &b), (&children[1], &b, &a)] {
        assert_ne!(child["session_id"], parent);
        assert!(child["task_id"].as_str().unwrap().starts_with("task-"));
        let text = child["output_excerpt"].as_str().unwrap();
        assert!(text.contains(token) && !text.contains(other));
        assert!(!child["source_anchors"].as_array().unwrap().is_empty());
    }
    let answer = tui.assistant_text(&facts);
    assert!(answer.contains(&a) && answer.contains(&b));
    assert!(answer.find(&a).unwrap() < answer.find(&b).unwrap());
    assert_eq!(
        std::fs::read(tui.workspace.join("child-a.txt")).unwrap(),
        a.as_bytes()
    );
    assert_eq!(
        std::fs::read(tui.workspace.join("child-b.txt")).unwrap(),
        b.as_bytes()
    );
    let packets = trace_packets(&tui);
    let parent_end = packets
        .iter()
        .rposition(|p| p["result"]["stopReason"] == "end_turn")
        .expect("real parent terminal response");
    for child in children {
        let id = child["task_id"].as_str().unwrap();
        let events = packets
            .iter()
            .enumerate()
            .filter(|(_, p)| {
                p["method"] == "_x.ai/session_notification"
                    && p["params"]["sessionId"] == parent
                    && p["params"]["update"]["subagent_id"] == id
            })
            .map(|(i, p)| (i, &p["params"]["update"]))
            .collect::<Vec<_>>();
        let starts = events
            .iter()
            .filter(|(_, e)| e["sessionUpdate"] == "subagent_spawned")
            .collect::<Vec<_>>();
        let ends = events
            .iter()
            .filter(|(_, e)| e["sessionUpdate"] == "subagent_finished")
            .collect::<Vec<_>>();
        assert_eq!(starts.len(), 1);
        assert_eq!(ends.len(), 1);
        assert_eq!(starts[0].1["parent_session_id"], parent);
        assert!(events
            .iter()
            .all(|(_, e)| e["child_session_id"] == child["session_id"]));
        assert_eq!(ends[0].1["status"], "completed");
        assert!(ends[0].1["tool_calls"].as_u64().unwrap() >= 1);
        assert!(events
            .iter()
            .any(|(_, e)| e["sessionUpdate"] == "subagent_progress"
                && e["tool_call_count"].as_u64().is_some_and(|n| n >= 1)));
        assert!(starts[0].0 < ends[0].0 && ends[0].0 < parent_end);
        tui.record("child-owned-wire-lifecycle", &json!({"task_id":id,"session_id":child["session_id"],"parent_session_id":parent,"start":starts[0].1,"end":ends[0].1,"progress_packets":events.len()-2}).to_string());
    }
    tui.record("two-real-children-parent-barrier", "one real task call waits for two distinct successful child sessions, preserves ordered exclusive unseen outputs and source anchors, and the parent consumes both results");
    finish(tui, "tool-wave-task-children");
}

fn start(case: &str, args: &[&str]) -> LiveTui {
    let mut tui = LiveTui::new(case);
    launch(&mut tui, args);
    tui
}

fn launch(tui: &mut LiveTui, args: &[&str]) {
    tui.launch(args);
    tui.wait_for("Aster", 45);
    tui.session_id();
    tui.dismiss();
}

fn request(tui: &mut LiveTui, label: &str, tool: &str, args: Value, followup: &str) -> Vec<Value> {
    let file = format!("request-{label}.json");
    std::fs::write(
        tui.workspace.join(&file),
        serde_json::to_vec(&args).unwrap(),
    )
    .unwrap();
    let prompt = format!("Read {file} once. Call {tool} exactly once with its exact JSON object as arguments. {followup}");
    let facts = tui.turn(&prompt, Some(b"\r"));
    let calls = facts
        .iter()
        .filter(|f| f["type"] == "model.turn" && f["payload"]["call"]["name"] == tool)
        .collect::<Vec<_>>();
    if !(tool == "git" && label == "git-branch") {
        assert_eq!(
            calls.len(),
            1,
            "exactly one requested model call is required"
        );
    }
    assert_eq!(
        calls[0]["payload"]["call"]["args"], args,
        "the actual call must preserve the fixed request arguments"
    );
    facts
}

fn outputs(facts: &[Value], name: &str) -> Vec<Value> {
    facts
        .iter()
        .filter(|f| f["type"] == "tool.prepared" && f["payload"]["prepared"]["tool_name"] == name)
        .map(|f| {
            let identity = &f["payload"]["prepared"]["identity"];
            let matches = facts
                .iter()
                .filter(|r| {
                    r["type"] == "tool.result" && r["payload"]["receipt"]["identity"] == *identity
                })
                .collect::<Vec<_>>();
            assert_eq!(matches.len(), 1, "one actual result per prepared identity");
            serde_json::from_str(matches[0]["payload"]["receipt"]["output"].as_str().unwrap())
                .unwrap()
        })
        .collect()
}

fn one(facts: &[Value], name: &str) -> Value {
    let mut results = outputs(facts, name);
    assert_eq!(results.len(), 1, "one actual {name} receipt is required");
    results.remove(0)
}

fn finish(mut tui: LiveTui, case: &str) {
    tui.checkpoint_session(case);
    tui.quit();
    tui.finish();
}

fn git(path: &Path, args: &[&str]) -> String {
    let result = Command::new("git")
        .args(args)
        .current_dir(path)
        .output()
        .unwrap();
    assert!(
        result.status.success(),
        "fixture git failed: {}",
        String::from_utf8_lossy(&result.stderr)
    );
    String::from_utf8(result.stdout).unwrap()
}

fn trace_packets(tui: &LiveTui) -> Vec<Value> {
    std::fs::read_to_string(tui.home.parent().unwrap().join("acp-traffic.jsonl"))
        .unwrap()
        .lines()
        .map(|line| serde_json::from_str::<Value>(line).unwrap()["message"].clone())
        .collect()
}
