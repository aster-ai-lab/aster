fn kimi_batch_partial_failure_retains_order_identity_and_successful_items() {
    let mut tui = start("tool-wave-batch", &[]);
    let a = format!("BATCH-A-{}", uuid::Uuid::new_v4());
    let b = format!("BATCH-B-中文-{}", uuid::Uuid::new_v4());
    std::fs::write(tui.workspace.join("batch-a.txt"), &a).unwrap();
    std::fs::write(tui.workspace.join("batch-b.txt"), &b).unwrap();
    let facts = request(&mut tui, "batch-mixed", "batch", json!({"invocations":[
        {"id":"first","tool":"read","args":{"file_path":"batch-a.txt"}},
        {"id":"missing","tool":"read","args":{"file_path":"missing-batch.txt"}},
        {"id":"last","tool":"read","args":{"file_path":"batch-b.txt"}}
    ],"max_concurrency":3}), "Report all three actual outcomes in input order. Do not retry or repeat any item, and do not call other tools.");
    let output = one(&facts, "batch");
    let metadata = &output["metadata"];
    assert_eq!(metadata["status"], "partial_failure");
    assert_eq!(metadata["total_count"], 3);
    assert_eq!(metadata["success_count"], 2);
    assert_eq!(metadata["failure_count"], 1);
    assert_eq!(metadata["failed_indices"], json!([1]));
    let items = metadata["results"].as_array().unwrap();
    assert_eq!(items.len(), 3);
    assert_eq!(
        items
            .iter()
            .map(|r| r["id"].as_str().unwrap())
            .collect::<Vec<_>>(),
        ["first", "missing", "last"]
    );
    assert_eq!(
        items
            .iter()
            .map(|r| r["success"].as_bool().unwrap())
            .collect::<Vec<_>>(),
        [true, false, true]
    );
    let text = output["text"].as_str().unwrap();
    assert!(text.contains(&a) && text.contains(&b) && text.contains("missing-batch.txt"));
    assert!(text.find(&a).unwrap() < text.find(&b).unwrap());
    assert_eq!(
        std::fs::read(tui.workspace.join("batch-a.txt")).unwrap(),
        a.as_bytes()
    );
    assert_eq!(
        std::fs::read(tui.workspace.join("batch-b.txt")).unwrap(),
        b.as_bytes()
    );
    tui.record("batch-three-real-outcomes", "three correlated results retain input order, exact success bytes and one missing-file error; successful items are not repeated");
    finish(tui, "tool-wave-batch");
}

