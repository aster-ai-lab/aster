float reference_fp8(uint8_t b) {
    const int s = b >> 7, e = (b >> 3) & 15, m = b & 7;
    float v;
    if (e == 0) v = std::ldexp((float) m, -9);                 // subnormal: m/8 * 2^-6
    else if (e == 15 && m == 7) v = NAN;
    else v = std::ldexp(1.0f + m / 8.0f, e - 7);
    return s ? -v : v;
}

